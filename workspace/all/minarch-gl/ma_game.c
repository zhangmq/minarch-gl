struct Game game;
struct retro_disk_control_ext_callback disk_control_ext;

void Game_open(char* path) {
	LOG_info("Game_open\n");
	int skipzip = 0;
	memset(&game, 0, sizeof(game));

	strcpy((char*)game.path, path);
	strcpy((char*)game.name, strrchr(path, '/')+1);
	strcpy((char*)game.alt_name, game.name); // default it

	// check first if the rom already is alive in tmp folder if so skip unzipping shit
	char tmpfldr[255];
	snprintf(tmpfldr, sizeof(tmpfldr), "/tmp/nextarch/%s", core.tag);
	char *tmppath = findFileInDir(tmpfldr, game.name);
	if (tmppath) {
		// Verify the file exists and has non-zero size (not being written or truncated)
		struct stat st;
		if (stat(tmppath, &st) == 0 && st.st_size > 0) {
			printf("File exists skipping unzipping and setting game.tmp_path: %s\n", tmppath);
			strcpy((char*)game.tmp_path, tmppath);
			skipzip = 1;
			// Update the game name to the extracted file name instead of the zip name
			if (CFG_getUseExtractedFileName())
				strcpy((char*)game.alt_name, strrchr(game.tmp_path, '/')+1);
		} else {
			printf("File exists but is empty or inaccessible, will re-extract: %s\n", tmppath);
		}
		free(tmppath);
	} else {
		printf("File does not exist in %s\n",tmpfldr);
	}

	// if we have a zip file
	if (suffixMatch(".zip", game.path) && !skipzip) {
		LOG_info("is zip file\n");
		int supports_zip = 0;
		int i = 0;
		char* ext;
		char exts[128];
		char* extensions[32];
		strcpy(exts,core.extensions);
		while ((ext=strtok(i?NULL:exts,"|"))) {
			extensions[i++] = ext;
			if (!strcmp("zip", ext)) {
				supports_zip = 1;
				break;
			}
		}
		extensions[i] = NULL;

		// if the core doesn't support zip files natively
		if (!supports_zip) {
			// extract zip file located at game.path to game.tmp_path
			// game.tmp_path is temp dir generated by mkdtemp
			LOG_info("Extracting zip file manually: %s\n", game.path);
			if(!extract_zip(extensions))
				return;
			// Update the game name to the extracted file name instead of the zip name
			if (CFG_getUseExtractedFileName())
				strcpy((char*)game.alt_name, strrchr(game.tmp_path, '/')+1);
		}
		else {
			LOG_info("Core can handle zip file: %s\n", game.path);
		}
	}

	// some cores handle opening files themselves, eg. pcsx_rearmed
	// if the frontend tries to load a 500MB file itself bad things happen
	if (!core.need_fullpath) {
		path = game.tmp_path[0]=='\0'?game.path:game.tmp_path;

		FILE *file = fopen(path, "r");
		if (file==NULL) {
			LOG_error("Error opening game: %s\n\t%s\n", path, strerror(errno));
			return;
		}

		fseek(file, 0, SEEK_END);
		game.size = ftell(file);

		rewind(file);
		game.data = malloc(game.size);
		if (game.data==NULL) {
			LOG_error("Couldn't allocate memory for file: %s\n", path);
			return;
		}

		fread(game.data, sizeof(uint8_t), game.size, file);

		fclose(file);
	}

	// m3u-based?
	char* tmp;
	char m3u_path[256];
	char base_path[256];
	char dir_name[256];

	strcpy(m3u_path, game.path);
	tmp = strrchr(m3u_path, '/') + 1;
	tmp[0] = '\0';

	strcpy(base_path, m3u_path);

	tmp = strrchr(m3u_path, '/');
	tmp[0] = '\0';

	tmp = strrchr(m3u_path, '/');
	strcpy(dir_name, tmp);

	tmp = m3u_path + strlen(m3u_path);
	strcpy(tmp, dir_name);

	tmp = m3u_path + strlen(m3u_path);
	strcpy(tmp, ".m3u");

	if (exists(m3u_path)) {
		strcpy(game.m3u_path, m3u_path);
		strcpy((char*)game.name, strrchr(m3u_path, '/')+1);
		strcpy((char*)game.alt_name, game.name); // default it
	}

	game.is_open = 1;
}

void Game_close(void) {
	if (game.data) free(game.data);
	// why delete tempfile? keep it for next time when loading the game its much faster from /tmp ram folder
	// if (game.tmp_path[0]) remove(game.tmp_path);
	game.is_open = 0;
	VIB_setStrength(0); // just in case
}

/* Directory part of a path, trailing slash kept ("/a/b/" for "/a/b/c.chd").
   Empty when there is no directory part, which is also what an empty path
   gives -- callers treat that as "cannot tell" and refuse. */
static void path_dir(const char* path, char* out, size_t size) {
	const char* slash = path ? strrchr(path, '/') : NULL;
	size_t len = slash ? (size_t)(slash - path) + 1 : 0;
	if (len >= size) len = size - 1;
	memcpy(out, path, len);
	out[len] = '\0';
}

/* Last component of a playlist entry.  get_image_path() returns the playlist
   text verbatim (relative entries stay relative), so this is the only part of
   it that can be compared with a path the frontend holds. */
static const char* path_base(const char* path) {
	const char* slash = path ? strrchr(path, '/') : NULL;
	return slash ? slash + 1 : path;
}

// Swap the disc in the emulated drive: the single entry point for that, and the
// only place that talks to the core's disk control interface.
//
// libretro.h gives the sequence verbatim (SET_DISK_CONTROL_INTERFACE: "The steps
// for swapping disk images are generally as follows") and the order is not
// cosmetic:
//
//   set_eject_state(true) -> replace_image_index(0, &info) -> set_eject_state(false)
//
// replace_image_index() is documented to need an ejected tray ("Virtual disk tray
// must be ejected when calling this") and a core that honours the contract answers
// false otherwise.  Closing the tray again is what actually loads the media:
// flycast's set_eject_state(false) calls emu.insertGdrom(disk_paths[disk_index]),
// yabasanshiro's calls Cs2ForceCloseTray() -> Cs2ChangeCDCore().  Replacing the
// image on a closed tray therefore left the old disc playing on both cores.
//
// minarch hands retro_load_game() a single disc file (never the playlist), so the
// core knows exactly one image and index 0 is the slot to replace: no
// add_image_index() and no image list on this side.  The playlist the *frontend*
// reads is only used to choose which file goes into that slot.
bool Game_changeDisc(char* path, GameDiscSwap* steps) {
	GameDiscSwap none = {0};
	if (!steps) steps = &none;
	*steps = none; // the report is filled in step by step; the caller's copy may be dirty

	if (!path || !path[0]) {
		steps->error = "no path";
		return false;
	}
	// that disc is already in the drive
	if (exactMatch(game.path, path)) {
		steps->noop = true;
		return true;
	}
	if (!exists(path)) {
		steps->error = "no such file";
		return false;
	}
	// cores without disk control have nothing to swap.  total_discs comes from the
	// playlist, not from the core, so this is reachable -- and it used to be a call
	// through a NULL function pointer.
	if (!disk_control_ext.set_eject_state || !disk_control_ext.replace_image_index) {
		steps->error = "core has no disk control interface";
		return false;
	}

	// Everything else the frontend derives per content -- menu.minui_dir, the
	// state/preview sidecar names, AUTO_RESUME -- comes from game.name and is not
	// recomputed after Game_open().  Loading a disc from another directory would
	// move it while the session keeps writing to the old names, so refuse before
	// touching game (see R6 in the requirement).
	char content_dir[MAX_PATH], target_dir[MAX_PATH];
	path_dir(game.m3u_path[0] ? game.m3u_path : game.path, content_dir, sizeof(content_dir));
	path_dir(path, target_dir, sizeof(target_dir));
	if (!content_dir[0] || !exactMatch(content_dir, target_dir)) {
		steps->error = "disc is outside the content directory";
		return false;
	}

	char previous[MAX_PATH];
	snprintf(previous, sizeof(previous), "%s", game.path);

	Game_close();
	Game_open(path);
	if (!game.is_open) {
		steps->error = "could not open the image";
		if (previous[0]) {
			Game_open(previous);
			steps->rolled_back = true;
		}
		return false;
	}

	struct retro_game_info game_info = {};
	game_info.path = game.tmp_path[0]?game.tmp_path:game.path; // as loaded
	game_info.data = game.data;
	game_info.size = game.size;

	// 1. Eject.  A core that already reports an open tray is not asked to eject
	// again: the header says a redundant call should answer true, but Beetle
	// Saturn answers false for it, and a false here would abort a good swap.
	steps->eject = (disk_control_ext.get_eject_state && disk_control_ext.get_eject_state())
		|| disk_control_ext.set_eject_state(true);

	if (steps->eject) {
		// 2. Put the image in.  Defensive branch: if this core did end up holding a
		// playlist (someone started the .m3u itself), replace() on slot 0 is not
		// what it expects -- use the index API and find the target by basename,
		// since its entries may be relative.  No match: fall back to replace(0).
		unsigned num = disk_control_ext.get_num_images ? disk_control_ext.get_num_images() : 0;
		if (num > 1 && disk_control_ext.set_image_index && disk_control_ext.get_image_path) {
			const char* want = path_base(path);
			for (unsigned i = 0; i < num && want && want[0]; i++) {
				char entry[MAX_PATH];
				if (!disk_control_ext.get_image_path(i, entry, sizeof(entry))) continue;
				if (!exactMatch(path_base(entry), want)) continue;
				if (disk_control_ext.set_image_index(i)) {
					steps->replace = true;
					steps->via = "set";
				}
				break;
			}
		}
		if (!steps->replace) {
			steps->replace = disk_control_ext.replace_image_index(0, &game_info);
			steps->via = "replace";
		}
		// 3. Close the tray whatever step 2 did: leaving it open strands the drive,
		// and this call is the one that performs the swap.
		steps->close = disk_control_ext.set_eject_state(false);
	}

	if (!steps->eject || !steps->replace || !steps->close) {
		// the drive still holds the previous disc, so the frontend's idea of the
		// content goes back to it
		if (previous[0]) {
			Game_close();
			Game_open(previous);
			steps->rolled_back = true;
		}
		return false;
	}

	putFile(CHANGE_DISC_PATH, path); // NextUI still needs to know this to update recents.txt
	return true;
}

int extract_zip(char** extensions)
{
	char buf[100];
	struct zip *za;
	int ze;
	if ((za = zip_open(game.path, 0, &ze)) == NULL) {
		zip_error_t error;
		zip_error_init_with_code(&error, ze);
		LOG_error("can't open zip archive `%s': %s\n", game.path, zip_error_strerror(&error));
		return 0;
	}

	mkdir("/tmp/nextarch",0777);
	char tmp_dirname[255];
	snprintf(tmp_dirname, sizeof(tmp_dirname), "%s/%s", "/tmp/nextarch",core.tag);
	mkdir(tmp_dirname,0777);

	int i, len;
	int fd;
	struct zip_file *zf;
	struct zip_stat sb;
	long long sum;
	for (i = 0; i < zip_get_num_entries(za, 0); i++) {
		if (zip_stat_index(za, i, 0, &sb) == 0) {
			len = strlen(sb.name);
			if (sb.name[len - 1] == '/') {
				sprintf(game.tmp_path, "%s/%s", tmp_dirname, basename((char*)sb.name));
			} else {
				int found = 0;
				char extension[8];
				for (int e=0; extensions[e]; e++) {
					sprintf(extension, ".%s", extensions[e]);
					if (suffixMatch(extension, sb.name)) {
						found = 1;
						break;
					}
				}
				if (!found) continue;

				sprintf(game.tmp_path, "%s/%s", tmp_dirname, basename((char*)sb.name));

				// Check if file already exists and has the correct size
				struct stat st;
				if (stat(game.tmp_path, &st) == 0 && st.st_size == sb.size) {
					// File already exists with correct size, skip extraction
					LOG_info("File already exists with correct size, skipping extraction: %s\n", game.tmp_path);
					return 1;
				}

				zf = zip_fopen_index(za, i, 0);
				if (!zf) {
					LOG_error( "zip_fopen_index failed\n");
					return 0;
				}

				// Try to create file exclusively first to avoid race condition
				fd = open(game.tmp_path, O_RDWR | O_CREAT | O_EXCL, 0644);
				if (fd < 0) {
					if (errno == EEXIST) {
						// File was created by another process, verify it's complete
						zip_fclose(zf);
						if (stat(game.tmp_path, &st) == 0 && st.st_size == sb.size) {
							LOG_info("File was created by another process, using it: %s\n", game.tmp_path);
							return 1;
						}
						// File exists but wrong size, try to truncate and rewrite
						fd = open(game.tmp_path, O_RDWR | O_TRUNC, 0644);
						if (fd < 0) {
							LOG_error("open failed after EEXIST: %s\n", strerror(errno));
							return 0;
						}
						zf = zip_fopen_index(za, i, 0);
						if (!zf) {
							LOG_error("zip_fopen_index failed on retry\n");
							close(fd);
							return 0;
						}
					} else {
						LOG_error("open failed: %s\n", strerror(errno));
						zip_fclose(zf);
						return 0;
					}
				}

				sum = 0;
				while (sum != sb.size) {
					len = zip_fread(zf, buf, 100);
					if (len < 0) {
						LOG_error( "zip_fread failed\n");
						close(fd);
						zip_fclose(zf);
						return 0;
					}
					write(fd, buf, len);
					sum += len;
				}
				close(fd);
				zip_fclose(zf);
				return 1;
			}
		}
	}

	if (zip_close(za) == -1) {
		LOG_error("can't close zip archive `%s'\n", game.path);
		return 0;
	}

	return 0;
}
